# frozen_string_literal: true

module Routing
  module Constraints
    # Общий контракт всех проверок допуска.
    #
    # Проверка допуска отвечает на вопрос «можно ли вообще отдать эту заявку
    # этому провайдеру» — да или нет, без оттенков. Вопрос «кого из допущенных
    # предпочесть» решают стратегии, и смешивать эти два уровня нельзя: ни одна
    # стратегия не вправе вернуть в игру провайдера, отсечённого здесь.
    #
    # Контракт метода: nil — провайдер проходит; Routing::Violation — не проходит,
    # с причиной и объяснением. Причина берётся из фиксированного списка
    # Routing::Reasons::SKIP, дословно совпадающего с эталоном организаторов;
    # объяснение обязано содержать числа, по которым видно, чего именно не
    # хватило.
    #
    # Устройство: одна проверка — один файл — одна ответственность. Классы, а не
    # методы, потому что реестр собирается из них списком, и добавить проверку
    # значит добавить файл и строку в реестр, не трогая планировщик.
    #
    # Сквозное правило про nil: отсутствующий лимит означает «ограничения нет»,
    # а не «лимит равен нулю». Так устроен fallback-провайдер, у которого не
    # заполнено ни одно ограничение, и проверка, забывшая про это, отсекла бы
    # его от всего подряд. Отсутствующие данные о самом провайдере (статус,
    # реквизиты) трактуются наоборот — не в его пользу.
    #
    # Дальше по коду: Routing::Constraints — реестр и порядок применения;
    # Routing::Violation и Routing::Details — форма ответа и тексты причин.
    class Base
      def self.violation(provider, operation, state)
        raise NotImplementedError, "#{name}.violation"
      end
    end
  end
end
