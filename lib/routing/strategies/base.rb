# frozen_string_literal: true

module Routing
  module Strategies
    # Общий контракт всех стратегий ранжирования.
    #
    # Стратегия отвечает на вопрос «кого из допущенных предпочесть». Она не
    # решает, кому можно, — это уже решили проверки допуска, и вернуть в игру
    # отсечённого провайдера стратегия не вправе.
    #
    # Ключевая идея: стратегия УПОРЯДОЧИВАЕТ, а не выбирает одного. Первый
    # элемент — основной выбор, весь список целиком — каскад на случай отказа.
    # Поэтому «второе место» тоже осмысленно: именно туда уйдёт заявка, если
    # первый провайдер ответит отказом.
    #
    # Контракт метода rank: вернуть перестановку входного списка. Не добавить,
    # не удалить, не подменить. Нарушение ловится сразу — Planner сверяет состав
    # до и после и падает с именем виновной стратегии, а не выдаёт тихо
    # испорченный каскад.
    #
    # Два сквозных запрета. Первый: не заглядывать в будущие заявки очереди —
    # обработка онлайновая, каждая заявка видит только текущее состояние.
    # Второй: не сравнивать дроби через float — только перекрёстным умножением
    # целых, иначе побайтовая воспроизводимость рассыпается на разных машинах.
    #
    # Метод explain — не украшение: его текст попадает в attempts и объясняет
    # жюри, почему выбран именно этот провайдер. Объяснение без чисел не
    # принимается.
    #
    # Дальше по коду: Routing::Strategies — реестр и то, как стратегия
    # выбирается по имени из конфига; Routing::Planner#plan — где ранжирование
    # встроено в построение каскада.
    class Base
      def rank(candidates, operation, state)
        raise NotImplementedError, "#{self.class}#rank"
      end

      def name
        raise NotImplementedError, "#{self.class}#name"
      end

      def explain(ranked, operation, state)
        raise NotImplementedError, "#{self.class}#explain"
      end
    end
  end
end
